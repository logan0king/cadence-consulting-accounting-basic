using CadenceAccounting.Models;
using System.Text;

namespace CadenceAccounting.Services
{
    public class ReportHtmlGenerator
    {
        public async Task<string> GenerateHtmlAsync(ReportDefinition report, ReportData data)
        {
            var html = new StringBuilder();
            
            // Start HTML document
            html.AppendLine("<!DOCTYPE html>");
            html.AppendLine("<html lang=\"en\">");
            html.AppendLine("<head>");
            html.AppendLine("    <meta charset=\"UTF-8\">");
            html.AppendLine("    <meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">");
            html.AppendLine("    <title>").Append(EscapeHtml(report.Title)).AppendLine("</title>");
            html.AppendLine("    <style>");
            html.AppendLine(GetCssStyles());
            html.AppendLine("    </style>");
            html.AppendLine("</head>");
            html.AppendLine("<body>");
            
            // Report header
            html.AppendLine("    <div class=\"report-header\">");
            html.AppendLine("        <h1 class=\"report-title\">").Append(EscapeHtml(report.Title)).AppendLine("</h1>");
            
            if (!string.IsNullOrEmpty(report.Description))
            {
                html.AppendLine("        <p class=\"report-description\">").Append(EscapeHtml(report.Description)).AppendLine("</p>");
            }
            
            html.AppendLine("        <div class=\"report-meta\">");
            html.AppendLine("            <span class=\"generation-date\">Generated: ").Append(DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss")).AppendLine("</span>");
            html.AppendLine("            <span class=\"execution-time\">Execution Time: ").Append(data.ExecutionTime.TotalMilliseconds.ToString("F0")).AppendLine(" ms</span>");
            html.AppendLine("        </div>");
            html.AppendLine("    </div>");
            
            // Report content
            html.AppendLine("    <div class=\"report-content\">");
            
            if (data.Rows.Any())
            {
                await AddDataTableAsync(html, data);
            }
            else
            {
                html.AppendLine("        <div class=\"no-data\">");
                html.AppendLine("            <p>No data available for the selected criteria.</p>");
                html.AppendLine("        </div>");
            }
            
            html.AppendLine("    </div>");
            
            // Report footer
            html.AppendLine("    <div class=\"report-footer\">");
            html.AppendLine("        <p>Report generated by Cadence Accounting System</p>");
            html.AppendLine("    </div>");
            
            html.AppendLine("</body>");
            html.AppendLine("</html>");
            
            return html.ToString();
        }

        private async Task AddDataTableAsync(StringBuilder html, ReportData data)
        {
            html.AppendLine("        <div class=\"data-table-container\">");
            html.AppendLine("            <table class=\"data-table\">");
            
            // Table header
            html.AppendLine("                <thead>");
            html.AppendLine("                    <tr>");
            foreach (var column in data.Columns)
            {
                html.Append("                        <th>").Append(EscapeHtml(column.Name)).AppendLine("</th>");
            }
            html.AppendLine("                    </tr>");
            html.AppendLine("                </thead>");
            
            // Table body
            html.AppendLine("                <tbody>");
            foreach (var row in data.Rows)
            {
                html.AppendLine("                    <tr>");
                foreach (var column in data.Columns)
                {
                    var value = row.ContainsKey(column.Name) ? row[column.Name] : "";
                    var displayValue = FormatCellValue(value);
                    html.Append("                        <td>").Append(EscapeHtml(displayValue)).AppendLine("</td>");
                }
                html.AppendLine("                    </tr>");
            }
            html.AppendLine("                </tbody>");
            html.AppendLine("            </table>");
            
            // Row count summary
            if (data.TotalRows > 0)
            {
                html.AppendLine("            <div class=\"table-summary\">");
                html.AppendLine("                <p>Total Rows: ").Append(data.TotalRows.ToString("N0")).AppendLine("</p>");
                html.AppendLine("            </div>");
            }
            
            html.AppendLine("        </div>");
        }

        private string FormatCellValue(object? value)
        {
            if (value == null || value == DBNull.Value)
                return "";
            
            if (value is DateTime dateTime)
                return dateTime.ToString("yyyy-MM-dd HH:mm:ss");
            
            if (value is decimal || value is double || value is float)
                return string.Format("{0:N2}", value);
            
            return value.ToString() ?? "";
        }

        private string EscapeHtml(string? text)
        {
            if (string.IsNullOrEmpty(text))
                return "";
            
            return text
                .Replace("&", "&amp;")
                .Replace("<", "&lt;")
                .Replace(">", "&gt;")
                .Replace("\"", "&quot;")
                .Replace("'", "&#39;");
        }

