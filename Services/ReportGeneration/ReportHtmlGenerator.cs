                    text-align: center;
                    font-size: 12px;
                    color: #95a5a6;
                }
                
                @media print {
                    body {
                        background: white;
                        padding: 0;
                    }
                    
                    .report-header,
                    .report-content {
                        box-shadow: none;
                        border: 1px solid #ddd;
                    }
                }
            ";
        }
    }
}
